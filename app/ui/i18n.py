_CATALOGUES: dict[Language, dict[str, str]] = {
    Language.ENGLISH: _EN,
    Language.PERSIAN: _FA,
}

_FA_DIGITS = "۰۱۲۳۴۵۶۷۸۹"


class Translator:
    """Runtime translator with locale-aware number formatting."""

    def __init__(self, language: Language = Language.ENGLISH) -> None:
        self._language = language

    @property
    def language(self) -> Language:
        return self._language

    @property
    def is_rtl(self) -> bool:
        return self._language is Language.PERSIAN

    def set_language(self, language: Language) -> None:
        self._language = language

    def t(self, key: str, **params: object) -> str:
        """Translate ``key``; unknown keys return the key itself."""
        catalogue = _CATALOGUES.get(self._language, _EN)
        text = catalogue.get(key) or _EN.get(key) or key
        if params:
            for name, value in params.items():
                text = text.replace("{" + name + "}", str(value))
        return text

    # Convenience so widgets can call ``tr("key")`` directly.
    __call__ = t

    def number(self, value: float | int, *, decimals: int = 0, grouping: bool = False) -> str:
        """Format a number for the active locale."""
        if isinstance(value, int) or (isinstance(value, float) and value.is_integer()):
            text = f"{int(value):,}" if grouping else str(int(value))
        else:
            text = f"{value:,.{decimals}f}" if grouping else f"{value:.{decimals}f}"
        if self._language is Language.PERSIAN:
            text = text.translate(str.maketrans("0123456789,", "۰۱۲۳۴۵۶۷۸۹٬"))
        return text



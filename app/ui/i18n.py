"""Internationalisation (spec §81, §82, §144).

A tiny, dependency-free translator with two rules that matter:

* **Keys are stable, values are display text.**  A missing key returns the key
  itself so the UI never crashes or shows a blank label — it shows the key,
  which is a bug signal rather than a mystery.
* **Numbers are formatted for the locale.**  Persian gets Eastern Arabic
  digits and the Persian thousands separator, English gets Latin digits.  This
  is what makes the Persian UI feel native rather than machine-translated.

Language can change at runtime without a restart (spec §81); the app rebuilds
its labels by re-emitting :data:`TOPIC_LANGUAGE`.
"""

